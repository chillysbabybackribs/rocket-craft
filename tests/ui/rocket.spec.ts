import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { test, expect, section } from './app'
import { assertOverlay, nativeViews } from './safeguards'

test('Craft Studio desktop self-check', async ({ rocket }) => {
  const { page, app, origin, profile, workspace } = rocket
  const message = page.getByRole('textbox', { name: 'Message', exact: true })
  const send = page.getByRole('button', { name: 'Send', exact: true })
  const stop = page.getByRole('button', { name: 'Stop', exact: true })
  const provider = async (name: string): Promise<void> => {
    await page.locator('.picker-trigger').click()
    await page.getByRole('menu', { name: 'Providers', exact: true }).getByRole('menuitemradio').filter({ hasText: name }).click()
  }
  const submit = async (text: string): Promise<void> => {
    const count = await page.locator('.turn').count()
    await message.fill(text)
    await send.click()
    await expect(page.locator('.turn')).toHaveCount(count + 1)
    await expect(page.locator('.turn').last().locator('.user-bubble')).toHaveText(text)
  }
  const complete = async (): Promise<void> => {
    await rocket.release()
    await expect(stop).toHaveCount(0)
    await expect(page.locator('.turn').last().locator('.prose')).toContainText('Complete. The controlled response finished.')
  }

  await test.step('Composer, folder selection, usage and model selection', async () => {
    await expect(send).toBeDisabled()
    await page.locator('.composer-folder').click()
    await expect(page.locator('.composer-folder')).toHaveAttribute('title', `Working folder: ${workspace}. Click to change.`)
    await message.fill('Draft first line')
    await message.press('Shift+Enter')
    await message.pressSequentially('Second line')
    await expect(message).toHaveValue('Draft first line\nSecond line')
    await expect(send).toBeEnabled()
    await (await section(page, 'Chats')).click()
    await expect(page.getByRole('menu', { name: 'Chat history' })).toContainText('Your chats will appear here.')
    await page.keyboard.press('Escape')
    await provider('Codex')
    await page.locator('.picker-trigger').click()
    await page.getByRole('menu', { name: 'Codex models' }).getByRole('menuitemradio').filter({ hasText: 'UI alternate' }).click()
    await expect(page.locator('.picker-trigger')).toContainText('UI alternate')
    await page.getByRole('button', { name: 'Codex usage: 25% used', exact: true }).hover()
    await expect(page.getByRole('group', { name: 'Codex usage', exact: true })).toContainText('25% Used')
    await message.click()
  })

  await test.step('Embedded page, navigation and browser tabs', async () => {
    await (await section(page, 'Browser')).click()
    const browser = await rocket.surface('browser')
    await expect(browser).toHaveTitle('UI page one')
    await browser.getByRole('textbox', { name: 'Test input' }).fill('Browser interaction works')
    await browser.getByRole('button', { name: 'Test button' }).click()
    await expect(browser.locator('#result')).toHaveText('Clicked successfully')
    await browser.getByRole('link', { name: 'Next page' }).click()
    await expect(browser).toHaveTitle('UI page two')
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await expect(browser).toHaveTitle('UI page one')
    await page.getByRole('button', { name: 'Forward', exact: true }).click()
    await expect(browser).toHaveTitle('UI page two')
    await page.getByRole('button', { name: 'New tab', exact: true }).click()
    await expect(page.locator('.btab')).toHaveCount(2)
    await expect(page.locator('.btab.is-active')).toHaveText('UI page one')
    await page.getByRole('textbox', { name: 'Address', exact: true }).fill(`${origin}/one`)
    await page.getByRole('textbox', { name: 'Address', exact: true }).press('Enter')
    await expect(page.locator('.btab.is-active')).toHaveText('UI page one')
    await page.getByRole('tab', { name: 'UI page two', exact: false }).click()
    await expect(page.locator('.btab.is-active')).toHaveText('UI page two')
    await page.getByRole('button', { name: 'Close tab: UI page one', exact: true }).click()
    await expect(page.locator('.btab')).toHaveCount(1)
    await (await section(page, 'Browser')).click()
    await expect(page.getByRole('region', { name: 'Browser', exact: true })).toHaveCount(0)
    await (await section(page, 'Browser')).click()
    await expect(page.locator('.btab.is-active')).toHaveText('UI page two')
    await expect(message).toHaveValue('Draft first line\nSecond line')
  })

  await test.step('Address suggestions overlay the page without moving it', async () => {
    const before = await page.locator('.browser-stage').boundingBox()
    const browser = (await nativeViews(app)).find(view => view.visible && view.url === `${origin}/two`)
    expect(browser).toBeDefined()
    await page.getByRole('textbox', { name: 'Address', exact: true }).fill(new URL(origin).host)
    const suggestions = await rocket.surface('suggestions')
    await expect(suggestions.locator('body')).toContainText('UI page two')
    expect(await page.locator('.browser-stage').boundingBox()).toEqual(before)
    await assertOverlay(app, browser!)
    await rocket.capture('browser-overlay')
    await page.getByRole('textbox', { name: 'Address', exact: true }).press('Escape')
    await message.click()
  })

  await test.step('Streaming completion and expandable tool output', async () => {
    await submit('UI check: stream')
    await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from codex.')
    await expect(stop).toBeVisible()
    expect(await rocket.request()).toMatchObject({ provider: 'codex', model: 'ui-alternate', cwd: workspace })
    await rocket.capture('streaming')
    await complete()
    await page.getByRole('button', { name: 'Worked · 1 step' }).click()
    await page.getByRole('button', { name: 'UI fixture' }).click()
    await expect(page.locator('.tool-output')).toHaveText('Fixture output is available.')
  })

  await test.step('Provider handoff keeps the conversation', async () => {
    await provider('Claude')
    await submit('UI check: stream')
    await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
    expect(await rocket.request()).toMatchObject({ provider: 'claude', handoffTurns: 1 })
    await complete()
    await expect(page.locator('.user-bubble')).toHaveCount(2)
  })

  await test.step('Stop interrupts a streaming response', async () => {
    await submit('UI check: stop')
    await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
    await stop.click()
    await expect(page.locator('.turn').last().locator('.notice')).toHaveText('Stopped')
    await expect(stop).toHaveCount(0)
    await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
  })

  await test.step('Failed turn is visible and the next turn can recover', async () => {
    await submit('UI check: fail')
    await expect(page.locator('.turn').last().locator('.notice.is-error')).toHaveText('Controlled UI test failure.')
    await expect(stop).toHaveCount(0)
    await submit('UI check: recover')
    await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
    expect((await rocket.request()).sessionId).not.toBeNull()
    await complete()
  })

  await test.step('Chat tabs preserve drafts and history reopens the conversation', async () => {
    await message.fill('Draft in existing chat')
    await page.getByRole('button', { name: 'New chat', exact: true }).click()
    await message.fill('Draft in new chat')
    await page.getByRole('tab', { name: 'UI check: stream', exact: true }).click()
    await expect(message).toHaveValue('Draft in existing chat')
    await page.getByRole('button', { name: 'Close tab: UI check: stream', exact: true }).click()
    await expect(message).toHaveValue('Draft in new chat')
    await (await section(page, 'Chats')).click()
    await page.getByRole('menuitem', { name: 'UI check: stream', exact: true }).click()
    await expect(page.locator('.turn')).toHaveCount(5)
    await expect(message).toHaveValue('Draft in existing chat')
    await message.fill('')
    await expect(send).toBeDisabled()
  })

  await test.step('Renderer reload restores persisted transcript and browser state', async () => {
    await page.reload()
    await expect(page.locator('.turn')).toHaveCount(5)
    await expect(page.locator('.turn').last().locator('.prose')).toContainText('Complete. The controlled response finished.')
    await expect(page.locator('.btab.is-active')).toHaveText('UI page two')
    await expect(page.locator('.notice.is-info')).toHaveText('Stopped')
    await expect(page.locator('.notice.is-error')).toHaveText('Controlled UI test failure.')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(880, 560))
    await expect(message).toBeVisible()
    await expect(send).toBeVisible()
    const box = await send.boundingBox()
    expect(box).not.toBeNull()
    const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
    expect(box!.x + box!.width).toBeLessThanOrEqual(viewport.width)
    expect(box!.y + box!.height).toBeLessThanOrEqual(viewport.height)
    await rocket.capture('minimum-size')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1360, 860))
    await rocket.capture('completed')
  })

  await test.step('Journal contains only the deliberately failed turn', async () => {
    const entries = (await readFile(join(profile, 'journal.jsonl'), 'utf8')).trim().split('\n').map(line => JSON.parse(line))
    const trouble = entries.filter(entry => entry.severity === 'warn' || entry.severity === 'error')
    expect(trouble).toHaveLength(1)
    expect(trouble[0]).toMatchObject({ source: 'turn', kind: 'turn-failed', message: 'claude (ui-default) failed: Controlled UI test failure.' })
  })
})
