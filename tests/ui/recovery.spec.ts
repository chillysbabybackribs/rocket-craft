import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { test, expect, section } from './app'

test('full app restart preserves completed chats, chosen model and browser tabs', async ({ rocket }) => {
  let page = rocket.page
  await page.locator('.composer-folder').click()
  await page.locator('.picker-trigger').click()
  await page.getByRole('menu', { name: 'Claude models' }).getByRole('menuitemradio').filter({ hasText: 'UI alternate' }).click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('UI check: stream')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.prose')).toHaveText('Streaming from claude.')
  const first = await rocket.request()
  await rocket.release()
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
  await expect(page.locator('.prose')).toContainText('Complete.')
  await (await section(page, 'Browser')).click()
  await (await rocket.surface('browser')).getByRole('link', { name: 'Next page' }).click()
  await expect(page.locator('.btab.is-active')).toHaveText('UI page two')
  const pid = rocket.app.process().pid
  await rocket.restart()
  expect(rocket.app.process().pid).not.toBe(pid)
  page = rocket.page
  await expect(page.locator('.turn')).toHaveCount(1)
  await expect(page.locator('.prose')).toContainText('Complete. The controlled response finished.')
  await expect(page.locator('.picker-trigger')).toContainText('UI alternate')
  await expect(page.locator('.composer-folder')).toHaveAttribute('title', `Working folder: ${rocket.workspace}. Click to change.`)
  await expect(page.locator('.btab.is-active')).toHaveText('UI page two')
  await expect(await rocket.surface('browser')).toHaveURL(`${rocket.origin}/two`)
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('UI check: recover')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
  const resumed = await rocket.request()
  expect(resumed.sessionId).not.toBeNull()
  expect(resumed.turnId).not.toBe(first.turnId)
  expect(resumed.model).toBe('ui-alternate')
  await rocket.release()
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
  await expect(page.locator('.turn')).toHaveCount(2)
  await rocket.capture('app-restarted')
  const entries = (await readFile(join(rocket.profile, 'journal.jsonl'), 'utf8')).trim().split('\n').map(line => JSON.parse(line))
  expect(entries.filter(entry => entry.severity !== 'info')).toEqual([])
})

test('host crash interrupts the active turn, reconnects and accepts another message', async ({ rocket }) => {
  const { page, app } = rocket
  await page.locator('.composer-folder').click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('UI check: stream')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.prose')).toHaveText('Streaming from claude.')
  const before = await rocket.request()
  const pid = await app.evaluate(({ app }) => {
    const host = app.getAppMetrics().find(metric => metric.name === 'Craft Studio Agent Host')
    if (!host) throw new Error('The isolated agent host was not found.')
    process.kill(host.pid, 'SIGKILL')
    return host.pid
  })
  await expect.poll(() => app.evaluate(({ app }) => app.getAppMetrics().find(metric => metric.name === 'Craft Studio Agent Host')?.pid)).not.toBe(pid)
  await expect(page.locator('.notice.is-info')).toHaveText('Stopped')
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
  await expect(page.locator('.user-bubble')).toHaveText('UI check: stream')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('UI check: recover')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.turn')).toHaveCount(2)
  await expect(page.locator('.turn').last().locator('.prose')).toHaveText('Streaming from claude.')
  expect((await rocket.request()).turnId).not.toBe(before.turnId)
  await rocket.release()
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
  await expect(page.locator('.turn').last().locator('.prose')).toContainText('Complete.')
  const entries = (await readFile(join(rocket.profile, 'journal.jsonl'), 'utf8')).trim().split('\n').map(line => JSON.parse(line))
  const trouble = entries.filter(entry => entry.severity !== 'info')
  expect(trouble).toHaveLength(1)
  expect(trouble[0]).toMatchObject({ source: 'main', kind: 'restart', severity: 'error' })
  await rocket.capture('host-recovered')
})
